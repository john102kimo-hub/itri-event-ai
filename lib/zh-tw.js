// S2T_WORDS 編譯成規則（批次 133 審查 F1）：有鄰字例外（before／after）的詞編成帶 lookbehind／lookahead 的 RegExp，
// 其餘走 split/join（快、而且跟舊版逐字相同）。ambiguous 的詞轉換時要先過 looksSimplified() 的門。
// 載入時就檢查：例外清單裡有 ] \ ^ - 會讓字元集合壞掉，寧可整支掛掉。
const S2T_WORD_RULES = S2T_WORDS.map(([from, to, guard = {}], idx) => {
  const { ambiguous = false, before = '', after = '' } = guard;
  if (/[\]\\^-]/.test(before + after)) throw new Error(`S2T_WORDS 例外清單含有特殊字元：${from}`);
  return {
    from, to, ambiguous, idx,
    re: before || after
      ? new RegExp(`${before ? `(?<![${before}])` : ''}${escapeRe(from)}${after ? `(?![${after}])` : ''}`, 'g')
      : null
  };
});
