// 這一小句是不是簡體：只在簡體出現的字（对照表的左邊、「发」）比只在繁體出現的字（对照表的右邊）多。
// 模型寫壞時通常是整句簡體（回報的警語就是），一句繁體裡夾一兩個漏網的簡體字不算——
// 那種句子只換掉那幾個字，歧義字維持原樣。平手算繁體：寧可漏轉，不要轉錯。
const SIMP_ONLY = new Set([...S2T_MAP.keys(), '发']);
const TRAD_ONLY = new Set(S2T_MAP.values());
function looksSimplified(clause) {
  let simp = 0, trad = 0;
  for (const ch of clause) {
    if (SIMP_ONLY.has(ch)) simp++;
    else if (TRAD_ONLY.has(ch)) trad++;
  }
  return simp > trad;
}

