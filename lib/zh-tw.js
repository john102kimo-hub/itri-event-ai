/**
 * 轉換後的文字裡還殘留哪些「簡體專用字」。去重、依出現順序、最多 10 個。
 * 語意是「轉完之後」：拿它去問一段沒轉過的台灣繁體，會把單字表裡的字（体、万…）也算進去。
 * 效能：逐字查 Set，O(n)——每個出口都會呼叫。
 */
export function findResidualSimplified(text) {
  const s = String(text ?? '');
  const found = [];
  for (let i = 0; i < s.length && found.length < RESIDUAL_MAX; i++) {
    const code = s.charCodeAt(i);
    if (code < 0x4E00 || code > 0x9FFF) continue; // 名單裡的字都在這個區段
    const ch = s[i];
    if (RESIDUAL_SET.has(ch) && !found.includes(ch)) found.push(ch);
  }
  return found;
}

