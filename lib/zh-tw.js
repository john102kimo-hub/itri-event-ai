// 詞和機構結尾之間不可能出現的字（句子的骨架）：遇到就停，表示這是一般句子、不是名稱。
// 「與／和／及」刻意不放：「信息與通信工程學院」「計算機與信息工程學院」是常見的學院名稱。
const NAME_BREAKERS = new Set([...'的了是在都也就還又很我你他她它這那其此該每各不可已讓給到去來說做要能有無沒等之所用以並且但而將被把對從為會']);
const NAME_TAIL_MAX = 12; // 詞和結尾之間最多隔幾個字（「長江存儲科技有限責任公司」隔 2 個字）
const NAME_SUFFIX_MAX = Math.max(...ORG_SUFFIXES.map((s) => s.length));
const NAME_CONTEXT = NAME_TAIL_MAX + NAME_SUFFIX_MAX; // 串流切段時，一個詞的判斷要往右看多遠

function followedByOrgSuffix(text, from) {
  for (let k = 0; k <= NAME_TAIL_MAX && from + k < text.length; k++) {
    for (const suffix of ORG_SUFFIXES) {
      if (text.startsWith(suffix, from + k) && (suffix !== '公司' || k >= 2)) return true;
    }
    // 先比結尾、再看是不是句子的骨架：「有限公司」的「有」本身就在 NAME_BREAKERS 裡
    if (NAME_BREAKERS.has(text[from + k])) return false;
  }
  return false;
}

// 編譯成一條 regex：由長到短排（sort 是穩定的，同長度維持上面的順序），同一個位置只會中一條。
const escapeRe = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const TERM_RULES = [
  ...TW_TERMS.map(([from, to, guard = {}]) => ({ from, to, before: guard.before || '', after: guard.after || '' })),
  ...TW_TERM_KEEP.map((from) => ({ from, to: from, before: '', after: '', keep: true }))
].sort((a, b) => b.from.length - a.from.length);
const TERM_BY_FROM = new Map(TERM_RULES.map((r) => [r.from, r]));
const TERM_RE = new RegExp(TERM_RULES.map((r) =>
  `${r.before ? `(?<![${r.before}])` : ''}${escapeRe(r.from)}${r.after ? `(?![${r.after}])` : ''}`
).join('|'), 'g');
const TERM_MAX_LEN = Math.max(...TERM_RULES.map((r) => r.from.length));

function applyTerms(text, onHit) {
  return text.replace(TERM_RE, (m, offset, whole) => {
    const rule = TERM_BY_FROM.get(m);
    if (!rule || rule.keep) return m;
    if (followedByOrgSuffix(whole, offset + m.length)) return m;
    if (onHit) onHit();
    return rule.to;
  });
}

