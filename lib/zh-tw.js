// 這一類的短小句（「然后，」「最后，」單獨成一小句）沒有簡體專用字可看，用門會漏轉。
//
// ⚠️ 加詞前先問自己：這個詞整個出現在正確的台灣繁體裡嗎，或是會跨在兩個詞的交界上嗎？會，就要加 ambiguous。
