//      繁體的小句沒有簡體專用字，永遠過不了這道門；
//   ② before／after ＝ 鄰字例外（跟 TW_TERMS 同款）：整句是簡體時，「机制作用」「选手表现」這種跨在兩個詞
//      交界上的也不能咬。例外的字簡繁兩種寫法都要列（机機、现現），因為這張表比對的是還沒轉過字的原文。
