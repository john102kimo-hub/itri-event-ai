// 簡體字防線：把要送出去的文字強制轉成台灣繁體。
//
// ⚠️ 這支檔案是「出口」，不是「建議」。CLAUDE.md 第 1、2 條：prompt 是請求、不是
// 保證，模型照做九成九，剩下那一次就是記者截圖傳給朱朱的那一次。所以**每一個會
// 把文字交到使用者手上的新出口，都要在這裡過一次**——LINE 回覆、網頁回應、語音
// 轉寫出來的逐字稿，一個都不能漏。
//
// 本來住在 api/line.js（那裡是第一個出口）。搬出來是因為媒體訓練那邊要接語音
// 轉寫：STT 引擎（Whisper 一族）對中文預設就是吐簡體字，那不是「偶爾」而是「每次」，
// 更非接不可。為了不動既有的 import，api/line.js 仍然 re-export 同一個函式。
// 回報的截圖：一整則回覆都是繁體，只有最後那句警語跑出簡體——
// 「内容仅供参考，以工研院官网新闻稿或发言为准。」
//
// 根因是整份 prompt 從頭到尾**沒有任何一條規則說「要用繁體」**。警語那條規則只寫了
// 「內容等同於⋯⋯」，模型就照自己的習慣重打一次，偶爾打成簡體。這是最常出現的一句
// （每則回答都有），所以踩到只是遲早。
//
// 兩層一起做，跟 Markdown 那次同一個結構：
//   ① prompt 加一條明確規則（見 askAnthropic() 的 ZH_TW_RULE）
//   ② **出口再轉一次**——規則是請求、不是保證。這一層才是真正的保證。
//
// ⚠️ 繁簡轉換最危險的地方是「一個簡體字對到多個繁體字」：发→發／髮、准→準／准、
// 后→後／后、里→裡／里、复→複／復／覆⋯⋯無腦轉會把本來正確的字改壞。所以拆成兩張表：
//   - S2T_WORDS：有歧義的字**只在詞裡轉**（「为准」→「為準」、「发言」→「發言」）
//   - S2T_CHARS：只收「這個簡體字在繁體中文裡根本不會單獨出現」的字，一對一，安全
// 兩張表都寧可漏轉也不要轉錯：漏轉是少數幾個字看起來怪，轉錯是把正確的內容改成錯的。
//
// 批次 133 起，字轉完之後還有兩層（都在下面，各有自己的說明）：
//   ① 用語：用繁體字寫出來的大陸用語（軟件、信息、芯片、人工智能……）轉成台灣的說法，
//      機構與公司名稱裡的詞不轉（TW_TERMS、TW_TERM_KEEP）；
//   ② 漏網偵測：轉完還看得到簡體專用字就記一行 log（findResidualSimplified），讓「字表漏了」不再是無聲的。
//      （它只是單字表的第二道網，不是「找出字表沒收的字」的工具；角色與限制見下面漏網偵測那一節。）
//
// 批次 133 審查（用約 2,200 萬字的 zh-tw 維基繁體語料與一份簡體對照語料實測）又收緊了幾件事，原則都是「寧可漏轉、不可轉錯」：
//   ③ 「台灣的人名、地名、專名真的會用」的字（丰庄党种适并万虫温）從單字表搬到 S2T_CONTEXT：只在詞裡、或這一小句看起來
//      是簡體時才轉。蘇姿丰、庄志明、手塚治虫、温嵐、党項、种師道、并州、李适不再被改成蘇姿豐、莊志明……
//   ④ 「兩邊共用字組成的詞」（制造／制作／制程／制品、手表、放松、采用／采集、由于、征求…）也只在簡體小句才轉，
//      而且跨在兩個詞交界上的（控制｜程式、選手｜表現、開放｜松山）有鄰字例外（S2T_WORDS 的第三個欄位）；
//   ⑤ 用語表拿掉風險大於效益的詞（算法、鼠標、光盤、塑料），補上機關名稱的保護。
//   反過來補了最大宗的漏網簡體字：于（99.4% 是「於」）、几、云，與發／髮、並／併的常見詞。
//
// 批次 133 審查（F1）：第三個欄位 { ambiguous, before, after } 給「左邊全是兩邊共用字」的詞用。
// 為什麼要有：「制造／制作／制程／制品」「手表」「放松」「采集」的每一個字，台灣的繁體裡都真的會出現——
// 「控制程式」「管制作為」「選手表現」「開放松山機場」「富采集團」整句都是正確的繁體，詞一律整段替換就
