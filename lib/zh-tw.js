export const ZH_TW_RULE = '用字：一律使用台灣慣用的繁體中文與台灣用語，絕對不可以出現簡體字（包含最後那句警語）。記者用英文或其他語言提問時才跟著改用該語言。';

// opts.terms（批次 133）：預設 true＝字轉完再轉用語。傳 { terms: false } 只轉「字」（簡→繁），不動用語。
// 為什麼要有：用語層（軟件→軟體、光伏→太陽光電…）是給**模型輸出**用的——模型愛用大陸說法，要在出口改成台灣說法。
// 但同仁在後台打的活動名稱、地點，報名者的姓名與媒體名稱，官網抓回來的標題與聯絡人，都是**名稱**，
// 照原樣顯示才對（批次 116 的教訓：「中科后里園區」被改成「後裡」）。這些地方仍然要擋簡體字
// （CLAUDE.md 第 1 條），所以不是整個不轉，只是不轉用語。預設行為一個字都沒變，既有呼叫端不用改。
// ⚠️ 只認 terms === false 才略過：`arr.map(toTraditionalTW)` 這種寫法會把索引（數字）當第二個參數傳進來，
// null、字串也一樣——這些都不是「要略過用語層」的意思，照預設轉。
export function toTraditionalTW(input, opts) {
  const withTerms = opts?.terms !== false;
  let out = String(input || '');
  if (!out) return out;
  let hits = 0, termHits = 0;
  // 一小句一小句轉（批次 116）：「是不是簡體」要看這一句原本的樣子，詞表換過之後就看不出來了。
  // 詞表與鄰字例外都不含標點，所以逐句轉跟以前整段轉的結果一樣，只差在歧義字多了 looksSimplified() 這道門。
  out = out.split(CLAUSE_SPLIT_RE).map((clause, k) => {
    if (k % 2 || !clause) return clause; // split 帶括號：奇數位是分隔符號本身
    const simplified = looksSimplified(clause);
    let candidates = null;
    for (const ch of new Set(clause)) {
      const list = S2T_WORD_INDEX.get(ch);
      if (list) candidates = candidates ? candidates.concat(list) : list;
    }
    if (candidates) {
      if (candidates.length > 1) candidates = candidates.slice().sort((a, b) => a.idx - b.idx); // 照表裡原本的順序
      for (const { from, to, ambiguous, re } of candidates) {
        if (ambiguous && !simplified) continue; // 繁體的小句（控制程式、選手表現）不碰這些詞
        if (!clause.includes(from)) continue;
        clause = re ? clause.replace(re, to) : clause.split(from).join(to);
      }
    }
    for (const { re, ch: target, to, alt, keepPrev = '', keepNext = '', forcePrev = '', forceNext = '', ambiguous } of S2T_CONTEXT) {
      if (!clause.includes(target)) continue;
      // 繁體小句裡的歧義字原樣保留；但有 forcePrev／forceNext 的字，鄰字是「只有簡體脈絡才會接在後面」的字時照轉
      if (ambiguous && !simplified && !forcePrev && !forceNext) continue;
      clause = clause.replace(re, (ch, i, whole) => {
        const prev = whole[i - 1] || '';
        const next = whole[i + 1] || '';
        // ⚠️ prev／next 要先確定「真的有這個鄰居」再去查例外表。
        // 舊版寫成 keepPrev.includes(prev)，而字串開頭時 prev 是空字串——
        // JS 的 String.includes('') **恆為 true**，所以這四個字只要出現在整段文字的
        // 頭或尾，就一律被當成例外、完全不轉。
        // 後果不是「選錯字」而是**簡體字真的送出去**：「發」的簡體「发」不是繁體字，
        // 「請勿轉发」這種以它收尾的句子，會原樣出現在記者的 LINE 訊息裡。
        // 這是整個專案第 1 條規則的強制出口，它自己有一個安靜的破口。
        const keep = (prev && keepPrev.includes(prev)) || (next && keepNext.includes(next));
        if (keep) return alt || ch;
        if (ambiguous && !simplified && !((prev && forcePrev.includes(prev)) || (next && forceNext.includes(next)))) return ch;
        return to;
      });
    }
    clause = clause.replace(/[一-鿿]/g, (ch, i, whole) => {
      const t = S2T_MAP.get(ch);
      if (!t) return ch;
      const k = S2T_CHAR_KEEP.get(ch);
      if (k && ((k.prev && whole[i - 1] && k.prev.includes(whole[i - 1])) || (k.next && whole[i + 1] && k.next.includes(whole[i + 1])))) return ch; // 拮据、腌臢
      hits++;
      return t;
    });
    // 批次 133：字轉完才轉用語（詞表左邊是繁體寫法）。同一小句之內做，跟專有名詞保護、串流切段共用同一個邊界。
    return withTerms ? applyTerms(clause, () => { termHits++; }) : clause;
  }).join('');
  if (hits) console.log(`[zh-tw] 出口轉繁體：換掉 ${hits} 個簡體字`);
  if (termHits) console.log(`[zh-tw] 出口轉用語：換掉 ${termHits} 個詞`);
  // 批次 133：轉完還看得到簡體專用字 = 字表漏了。只記字、不記全文（全文可能是記者的提問或未發布的稿）。
  const leaked = findResidualSimplified(out);
  if (leaked.length) console.warn(`[zh-tw-leak] 殘留簡體字：${leaked.join('、')}`);
  return out;
}

// ── 串流出口（批次 82）─────────────────────────────────────────────────────
// 網頁版問答是一小段一小段（SSE）送到記者畫面上的，可是 toTraditionalTW() 要看前後文
// 才轉得準：詞表（「头发」→「頭髮」）與鄰字規則（后／发／准／里）都要看左右鄰居。
// 每收到一小段就轉一次的話，一個詞被切在兩段中間就會轉錯（「头」｜「发」→「頭發」）。
//
// 做法：只在「標點或空白」的後面切段。詞表裡沒有任何一個詞含標點，鄰字規則的例外表裡
// 也沒有標點——所以在標點後面切開、一段一段轉，結果跟整篇一次轉逐字相同
// （test/test-review82.mjs 拿整篇一次轉與各種切法逐段轉比對）。中文的標點很密，實際上每幾個字
// 就送得出一段，記者感覺不到延遲。
//
// 一直等不到標點（極少見，例如一長串沒有標點的字）時，囤到 STREAM_HOLD_MAX 個字就先送，
// 留最後幾個字等下一段——寧可極少數情況下漏轉一個字，也不要讓畫面停住不動。
// 批次 116：跟 toTraditionalTW() 的「一小句」用同一組字元（CLAUSE_PUNCT），不能各寫一份。
//
// 批次 133：用語詞表最長 TERM_MAX_LEN 個字（「數字化轉型」），而且詞可能被切在兩段中間
// （「集成電｜路」）。以前留最後兩個字，現在要留得下最長的詞：
//   ① 留尾至少 TERM_MAX_LEN + 1 個字（詞完整地躺在尾巴裡，下一輪才看得到它的完整樣子）；
//   ② 切點本身還要避開「某個詞的判斷範圍」——詞的前一個字（before 例外）、後面 NAME_CONTEXT 個字
//      （專有名詞保護、after 例外要往右看）。切點落在這個範圍裡，這個詞兩邊看到的前後文就不一樣，
//      「演｜算法」「中國信息通信研｜究院」會被轉錯或轉成別的樣子（見 forcedCutPoint()）。
//   找不到安全切點就再多等一下，等到 STREAM_HOLD_HARD 還是找不到才硬切（畫面不能一直停住）。
// 標點處的切法不受影響——詞表、例外、名稱保護都不跨標點。
const STREAM_CUT_RE = new RegExp(`[${CLAUSE_PUNCT}]`);
const STREAM_HOLD_MAX = 80;
const STREAM_HOLD_HARD = STREAM_HOLD_MAX * 3;
const STREAM_TAIL_KEEP = Math.max(2, TERM_MAX_LEN + 1);

// 強制切段時的切點：從「留尾之後」往左找第一個不落在任何詞的判斷範圍內的位置；找不到回 0。
// ⚠️ 要找的是「文字裡出現的每一個詞」，**包含被 before／after 例外擋下、整篇轉時不會轉的**：
// 「演｜算法」整篇轉時 TERM_RE 不會中（before 例外），但切在中間，下半段「算法…」就看不到前面的「演」，
// 會被轉成「演演算法」。所以這裡掃的是沒有例外的左邊本身，而且每個位置都找（含互相重疊的）。
//
// 批次 133 審查（F8）：S2T_WORDS 的詞、S2T_CONTEXT 的歧義字（前後一個字的例外）、S2T_CHAR_KEEP 也是一樣的道理——
// 「复｜杂」「肝｜脏」「烟｜草」被切在兩段中間，上半段只看到半個詞，簡體的「复」就漏出去了（整篇轉卻會轉成「複雜」）。
// 它們比對的是**還沒轉過字的原文**，所以直接掃 raw；詞前後各一個字（before／after 例外）也算在判斷範圍內。
// 限制（誠實寫）：ambiguous 的詞與字要看「整小句是不是簡體」，強制切段把一個超長小句切成兩半之後，兩半各自數簡體字，
// 可能跟整篇一次轉的結果不同。要發生得同時：連續 80 字以上沒有任何標點、而且簡體證據在兩半分布得很不均勻，實務上極少。
const CUT_GUARD_CHARS = new Set([...S2T_CONTEXT.map((r) => r.re.source), ...S2T_CHAR_KEEP.keys()]);
function forcedCutPoint(raw) {
  let cut = raw.length - STREAM_TAIL_KEEP;
  if (cut <= 0) return 0;
  // 模型吐的是簡體，詞表左邊是繁體：先逐字轉成繁體再找（字表一對一，長度不變，位置對得上）
  let text = '';
  for (let i = 0; i < raw.length; i++) text += S2T_MAP.get(raw[i]) ?? raw[i];
  const unsafe = new Uint8Array(text.length + 1);
  for (const { from } of TERM_RULES) {
    for (let i = text.indexOf(from); i >= 0; i = text.indexOf(from, i + 1)) {
      const end = Math.min(text.length, i + from.length + NAME_CONTEXT);
      for (let p = i; p <= end; p++) unsafe[p] = 1; // p = i 也算：它的前一個字（before 例外）會落在另一邊
    }
  }
  // S2T_WORDS 的詞：[i, i + 長度] 都不能切（切在詞前面會丟掉 before 例外的字，切在後面會丟掉 after 例外的字）
  for (const { from } of S2T_WORD_RULES) {
    for (let i = raw.indexOf(from); i >= 0; i = raw.indexOf(from, i + 1)) {
      for (let p = i; p <= Math.min(raw.length, i + from.length); p++) unsafe[p] = 1;
    }
  }
  // 歧義字／例外字：它的前一個字與後一個字決定要不要轉，切在它前後都會讓兩邊看到的鄰居不同
  for (let i = 0; i < raw.length; i++) {
    if (CUT_GUARD_CHARS.has(raw[i])) { unsafe[i] = 1; unsafe[i + 1] = 1; }
  }
  while (cut > 0 && unsafe[cut]) cut--;
  return cut;
}

export function createTraditionalStream() {
  let pending = '';
  return {
    /** 餵進模型剛吐出的一小段，回傳「現在可以安全送出」的已轉換文字（可能是空字串）。 */
    push(chunk) {
      pending += String(chunk ?? '');
      let cut = -1;
      for (let i = pending.length - 1; i >= 0; i--) {
        if (STREAM_CUT_RE.test(pending[i])) { cut = i + 1; break; }
      }
      if (cut <= 0) {
        if (pending.length < STREAM_HOLD_MAX) return '';
        cut = forcedCutPoint(pending);
        if (cut <= 0) {
          if (pending.length < STREAM_HOLD_HARD) return ''; // 這一帶都是詞的判斷範圍，再等一下
          cut = pending.length - STREAM_TAIL_KEEP;
        }
        // 不要把一個 emoji（兩個 UTF-16 單位）切成兩半
        const c = pending.charCodeAt(cut - 1);
        if (c >= 0xD800 && c <= 0xDBFF) cut -= 1;
      }
      const out = pending.slice(0, cut);
      pending = pending.slice(cut);
      return toTraditionalTW(out);
    },
    /** 串流結束：把囤著的最後一段轉完送出。 */
    flush() {
      const out = toTraditionalTW(pending);
      pending = '';
      return out;
    }
  };
}

