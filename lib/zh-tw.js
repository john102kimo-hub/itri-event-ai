//   ② 例外的字也不能是簡體字；
//   ③ **冪等**：每一條的右邊再轉一次必須原封不動（右邊不能含任何一條的左邊，
//     「演算法」裡的「算法」靠 before 例外擋住）。
{
  const bad = [];
  const seen = new Set();
  const isSimp = (s) => [...s].some((ch) => S2T_MAP.has(ch));
  for (const r of TERM_RULES) {
    if (seen.has(r.from)) bad.push(`重複：${r.from}`);
    seen.add(r.from);
    if (!r.keep && r.from === r.to) bad.push(`沒有轉換：${r.from}`);
    if (isSimp(r.from) || isSimp(r.to) || isSimp(r.before) || isSimp(r.after)) bad.push(`含簡體字：${r.from}`);
    if (applyTerms(r.to) !== r.to) bad.push(`不冪等：${r.from}→${r.to}`);
  }
  for (const s of [...ORG_SUFFIXES, ...NAME_BREAKERS]) if (isSimp(s)) bad.push(`機構結尾含簡體字：${s}`);
  if (bad.length) throw new Error(`TW_TERMS 格式錯誤：${bad.join('、')}`);
}

