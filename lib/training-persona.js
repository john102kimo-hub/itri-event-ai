//
// 一、媒體名稱。舊版 prompt 寫的是「虛構媒體名稱」，模型每次自己編一個。主管的
// 回報很直接：練起來不像真的。真實的媒體訓練，第一件事就是告訴受訓者「今天來的是
// 哪一家」——因為《工商時報》和《公視》想要的東西完全不同，該準備的話也不一樣。
// 改成從下面這份真實台灣媒體名單裡挑，而且**在程式裡挑好、把名字直接寫進 prompt**，
// 不是叫模型「請用真實的台灣媒體」。理由是 CLAUDE.md 第 2 條：那樣寫模型會照做
// 九成九，剩下那一次就會冒出一家不存在的報紙，或更糟——一家對岸的媒體。
//
// 二、主管是誰。同一場記者會，院長被問的跟計畫主持人被問的不是同一批問題：
// 院長要回答資源配置與政策，計畫主持人要回答技術做不到什麼。舊版不分，出來的題目
// 對誰都只有七分準。身分同樣走白名單：前端傳什麼進來都先收斂成下面這幾種之一，
// 不明就用通用版，不讓任意字串直接拼進 prompt。
//
// 純函式，沒有網路與環境變數，test/training.test.mjs 直接 import 來測。

