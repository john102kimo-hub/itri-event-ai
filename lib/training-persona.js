const OUTLET_BY_ID = new Map(MEDIA_OUTLETS.map((o) => [o.id, o]));

/**
 * 收斂成名單裡的一家。傳進來的 id 不在名單上（前端舊版、有人手改參數、亂送）
 * 一律當作沒指定，隨機挑一家——**絕不會回一個名單外的媒體名稱**，
 * 這就是「真實媒體」這件事的保證所在，不是 prompt 裡那句請求。
 */
export function resolveOutlet(id) {
  const hit = OUTLET_BY_ID.get(String(id || '').trim());
  if (hit) return hit;
  return MEDIA_OUTLETS[Math.floor(Math.random() * MEDIA_OUTLETS.length)];
}

