// 之後，接著打「技術呢」——口語的追問，想換個主題繼續問（「那技術方面呢」的省略
// 講法），完全沒有反應，體感是「卡住了，無法持續聊」。根因跟「你能做啥」那次一樣：
// 這句話沒對到任何規則，掉進 routeIntent()，AI 判成 other，群組裡沒被直接 @ 到時
// other 是安靜門檻。「技術」後面接語助詞「呢／嗎」是很自然的口語追問句型，補進這條
// 規則，跟「想問什麼技術」同樣的處理方式（先問想了解哪一項技術）。
//
// ⚠️ 刻意不讓「技術」單獨兩個字也命中：test-flow.mjs 情境 12（邀訪聯絡窗口分工）
// 有個既有情境專門測「只打配置好的關鍵字的一部分（例如『技術規格』只打『技術』）
// 不該算命中，要落回一般問答」——這裡如果讓裸詞「技術」也觸發 tech_query，會把
// 那個既有情境攔截掉，變成兩邊互相踩線。「技術呢／技術嗎」有明確的語助詞，跟裸詞
// 「技術」是不同的輸入，不會互相衝突。
//
// 主動盤點再補上「技術查詢」——跟清單裡已有的「技術詢問」是近義詞（查詢／詢問），
// 記者兩種講法都可能打，補上不影響上面「技術」裸詞不命中的防線（「技術查詢」四個
// 字是完整詞組，不是裸詞）。
const TECH_QUERY_EXACT_RE = /^(想問什麼技術|工研院技術|技術詢問|技術查詢)[?？!！。]?$|^技術(呢|嗎)$/;

// 問「工研院是什麼」「介紹一下工研院」這種在問**機構本身**（不是某項技術、不是某場
// 活動）的問句（批次 65，回報：「可否如果有人問介紹工研院等相關字眼，可否抓官網
// 資料，並告知院長為張培仁、董事長為吳政忠」）。
//
// 這句話原本沒對到任何規則，會掉進 routeIntent()：那支的 tech_query 說明裡寫著
// 「問『工研院最近發了哪些新聞／新聞稿』這種不指定技術領域的問題也算 tech_query，
// tech_keyword 留空」（見 lib/router.js），模型很容易把「介紹一下工研院」也讀成同一類，
// 送去 answerTechQuery() 查「最近新聞」——答非所問：記者要的是機構簡介跟經營團隊，
// 不是最新聞稿清單。
//
// 跟院長／董事長姓名這種「錯了會很難看」的事實一樣，這支刻意不靠 AI 現場答、也不靠
// 每次即時去抓官網頁面解析（HTML 結構隨時可能改版，解析壞掉又是另一種「已讀不回」）：
// 直接寫死一份審過的簡介 + 兩個人名，來源是工研院官網「關於我們」分類頁（見
// ORG_INTRO_TEXT 裡附的連結），2026-09-16 人工核對過官網當下內容。經營團隊異動不會
// 常發生，但**真的換人時這裡要記得手動更新**——跟這個帳號其他所有「絕對不能講錯的
// 事實」同一個道理，寧可資料偶爾過時（記者還能點連結去官網核對），也不要讓模型自己
// 猜一個名字出來。
//
// 判準跟其他 *_EXACT_RE 一樣嚴格、整句錨定：只接「工研院是什麼／簡介／院長是誰」這種
// 問句本身就是在問機構整體的講法。「介紹一下工研院在半導體的技術」這種**後面還接著
// 具體主題**的問句不命中，繼續走 tech_query 查半導體——不能因為句子裡有「工研院」
// 兩個字就攔截掉所有帶主題的提問。
const ORG_INTRO_RE = /^工研院(簡介|是什麼|是做什麼的|是什麼機構|是什麼樣的機構|是什麼單位|是什麼公司|是什麼組織)[?？!！。]?$|^(介紹|簡單介紹|簡介)\s*(一下)?\s*工研院[?？!！。]?$|^工研院\s*(的)?\s*(院長|董事長)\s*是誰[?？!！。]?$|^(現任|現在的|目前的)?\s*(院長|董事長)\s*是誰[?？!！。]?$/;

// 「最近工研院有哪些新聞」——問的是工研院最近發了哪些新聞稿，**沒有指定技術領域**。
//
// 實際回報（附截圖）：群組裡打「米亞 最近工研院有哪些新聞」，米亞回的是【近期活動】
// 行事曆。記者又追問一次「最近發的新聞稿麼」。這是答非所問：問的是新聞稿，回的是
// 記者會場次表——兩件事在這個帳號裡是不同的資料來源（新聞稿在工研院官網新聞中心，
// 場次在 events 表）。
//
// 根因：這句話沒對到任何規則，掉進 routeIntent()，AI 看到「最近⋯有哪些」這個跟
// 「最近有哪些活動」幾乎一樣的句型就判成 calendar。而 lib/itri-news.js 的
// fetchItriNews() 早就留好了「不給關鍵字就回最新新聞」這條路（那支的註解寫著
// 「這個分支是給之後萬一有『不指定技術、直接看工研院最新動態』需求時的退路」），
// 只是從來沒有入口叫得到它。
//
// ⚠️ 判斷方式跟其他 *_EXACT_RE 一樣嚴，但改用「扣掉之後還剩什麼」而不是一條長
// regex：把核心詞（新聞／新聞稿／消息）拿掉，再把時間詞、疑問詞、語助詞、「工研院」
// 全部扣掉，如果一個字都不剩，那就是在問「最新新聞」這件事本身。只要還剩下任何字
// （「半導體」「這場」），那就是有主題的問題，不歸這裡管——「半導體最近有什麼新聞」
// 要走 tech_query 拿關鍵字去搜，「這場的新聞稿」要走該場活動的問答。
// 這個寫法比長 regex 好維護，也天然擋掉了誤判：漏收一個語助詞只會讓這條不命中
// （退回原本的 AI 路由），不會反過來把有主題的問題吃掉。
// ⚠️ 核心詞刻意只收「新聞稿」「新聞」，不收「消息」。群組裡命中 detectMetaIntent()
// 就會回答（見 api/line.js handleGroupMessage()），而「最近有什麼消息」在記者群裡
// 十之八九是人在問人，不是在叫米亞——多收一個口語詞換來的是米亞插話，划不來。
const NEWS_CORE_RE = /新聞稿|新聞/g;
const NEWS_FILLER_RE = /米亞|工研院|itri|最近|近期|最新|這陣子|這幾天|今天|本週|這週|這個月|有哪些|有那些|有什麼|有沒有|哪些|那些|什麼|發表|發布|發佈|發過|發的|發了|出了|新的|請問|想看|想知道|給我|有|發|的|了|嗎|呢|麼|沒|吧|喔|press release|news|[\s?？!！。，,、~～]/gi;

export function isLatestNewsQuestion(text) {
  const s = String(text || '').trim();
  if (!s || s.length > 30) return false;          // 太長多半是一整句有主題的提問
  const withoutCore = s.replace(NEWS_CORE_RE, '').trim();
  if (withoutCore === s) return false;            // 根本沒提到新聞／消息
  // ⚠️ 裸詞「新聞」刻意不命中，理由跟上面 TECH_QUERY_EXACT_RE 不讓裸詞「技術」命中
  // 一樣：兩個字太容易是別句話的一部分（邀訪窗口的關鍵字裡就有「新聞稿」）。要有
  // 時間詞或疑問語氣才算一句在問「最近有什麼新聞」的話。
  if (!withoutCore) return false;
  return withoutCore.replace(NEWS_FILLER_RE, '').trim() === '';
}

// 綁定中問「新聞稿」，到底是問「這一場的」還是「工研院最近的」？（批次 72）
//
// 批次 61 修的是 routeIntent() 那條路（「新聞稿」三個字被 AI 判成全站新聞）。但盤點時
// 發現**規則層在更前面**：isLatestNewsQuestion() 會吃下「有新聞稿嗎」「給我新聞稿」
// 「新聞稿呢」「新聞稿發了嗎」——扣掉核心詞與語助詞剛好一個字不剩——於是在
// handleMetaIntent() 直接被送去 answerLatestNews()，連 routeIntent() 都輪不到。
// 記者掃了某一場的 QR code、在那一場裡問「有新聞稿嗎」，拿到的是工研院官網最新五則，
// 正是批次 61 回報的那個症狀，只是換了一條路重演。
//
// 判準：句子裡有「指向全院／一段時間」的字（工研院、最近、最新、這個月、有哪些…）
// 才是在問全站新聞；沒有的話，綁定中就是在問這一場。沒綁定時不受影響（沒有「這一場」
// 可以回答，維持原本的全站新聞）。
const ORG_WIDE_NEWS_RE = /工研院|itri|最近|近期|最新|這陣子|這幾天|本週|這週|這個月|有哪些|有那些|哪些|那些|press release|news/i;
export function isOrgWideNewsAsk(text) {
  return ORG_WIDE_NEWS_RE.test(String(text || ''));
}

// 「謝謝」「了解」「好的收到」這種收尾語（批次 72）。
//
// 盤點時把一批收尾語丟進規則層，發現它們在「沒有綁定」時會落到 looksLikeBareTopic()
// ——「好的謝謝」「謝謝米亞」「了解」「收到謝謝」「先這樣」全部是 2～8 個字、沒有疑問詞，
// 被當成**主題詞**複誦回去：「『謝謝米亞』我可以從兩個方向幫您找 🙂」，底下還掛著
// 「謝謝米亞的產業趨勢」「工研院的謝謝米亞技術」兩顆按鈕——正是批次 27 開頭那段警告
// 在講的難看，只是那次的例子是「天氣如何」。記者最常沒綁定的時機，恰好是剛問完產業
// 趨勢／技術（那兩條路不綁場次）之後說一聲謝謝。
//
// 做法是把整句拆成「收尾用的字」，拆完一個字都不剩才算：`謝謝，那成本呢` 拆完還剩
// 「那成本呢」，不算——後面接著真正問題的句子一律照常走問答。
//
// 回傳 'thanks'（道謝）｜'ack'（了解／收到）｜null。
const COURTESY_THANKS_RE = /謝謝|感謝|多謝|感恩|謝啦|謝囉|謝了|thank ?you|thanks|thx|tks|幫大忙了|很有幫助|有幫助|太棒了|太棒|很棒|好棒|超棒|太好了|讚/gi;
const COURTESY_ACK_RE = /好的|好喔|好唷|好哦|好啊|好滴|了解|瞭解|知道了|收到|沒問題|沒事了|不用了|先這樣|就這樣|可以了|ok|okay|嗯嗯|嗯/gi;
const COURTESY_FILLER_RE = /米亞|你們|妳們|大家|你|妳|您|很多|非常|真的|超|辛苦了|啦|囉|喔|哦|唷|耶|呀|了|的/g;
export function detectCourtesy(text) {
  const s = String(text || '').toLowerCase().replace(/[\s\p{P}\p{S}\p{M}‍]/gu, '');
  if (!s || s.length > 16) return null;
  const hasThanks = s.search(COURTESY_THANKS_RE) !== -1;
  const hasAck = s.search(COURTESY_ACK_RE) !== -1;
  if (!hasThanks && !hasAck) return null;
  let rest = s.replace(COURTESY_THANKS_RE, '').replace(COURTESY_ACK_RE, '').replace(COURTESY_FILLER_RE, '');
  // 「好」單獨一個字只在已經有收尾語的句子裡算（「好謝謝」「嗯嗯好」）；整句只有
  // 「你好」這種招呼時 hasThanks、hasAck 都是 false，早在上面就回 null 了。
  rest = rest.replace(/好/g, '');
  if (rest) return null;
  return hasThanks ? 'thanks' : 'ack';
}

// 提問語氣的開頭詞——用來擋掉「把一句問題誤認成活動名稱」。跟 api/line.js 的
// looksLikeNameOrSkip() 是同一類防線，但那支管的是媒體名稱，這支管的是活動名稱，
// 兩邊的誤判後果不同（那邊是少記一個媒體名，這邊是整個換錯場次），所以分開維護。
const QUESTION_LEAD_RE = /^(請問|為什麼|為何|什麼|怎麼|如何|哪裡|哪一|哪些|何時|多少|是否|能不能|可不可以|可以|會不會|有沒有|給我|請給|麻煩|幫我|提供|想問|想知道|想要|需要|介紹|說明一下)/;

// ── 「我要找真人」（批次 81）──────────────────────────────────────────────
// 背景：2026-09 世新大學砍掉系辦、改叫師生問 AI，引發大量批評——核心是「找不到人」：
// AI 答不出來、又沒有真人可以轉，使用者被困在 AI 裡。朱朱要求確認我們不會發生一樣的事。
//
// 盤點時實測：記者打「我要找真人」「可以跟承辦人講話嗎」「給我電話」，拿到的是兜底的
// 「這題我這邊查不到耶」，一個人名都沒有；打「轉人工」更糟，被當成主題詞複誦成「轉人工的
// 產業趨勢」。兜底那支刻意禁止模型講聯絡方式（怕它編電話），程式卻沒有補上真人出口。
//
// 「找得到真人」是這個帳號絕對不能失手的事（CLAUDE.md 第 2 條），所以用字面比對、寫死回覆，
// 不交給模型。判準刻意寬：多攔一句「給我電話」的代價只是多拿到一份聯絡人，漏攔的代價
// 是記者覺得被 AI 困住。
const HUMAN_WORD = '(真人|真的人|活人|人工|客服|承辦人|承辦同仁|公關人員|公關同仁|公關|工作人員|同仁|窗口)';
const HUMAN_REQUEST_RES = [
  // 「找真人」「轉人工」「我要找承辦人」「可以跟公關同仁講話嗎」
  new RegExp(`^(米亞)?[\\s，,]*(我|請)?(要|想|想要|可以|能不能|能否|可否)?(直接)?(找|轉|轉給|聯絡|聯繫|跟|和|問)\\s*${HUMAN_WORD}(講|說|談|聊|接|處理|服務|回覆)?(話|一下)?(嗎|呢|好嗎)?[\\s\\p{P}\\p{S}]*$`, 'u'),
  /^(有人在嗎|有人嗎|有真人嗎|有沒有真人|是真人嗎|有人可以回答嗎|有人可以幫忙嗎)[?？!！。～~]*$/,
  /(轉|找)(真人|人工|客服)/,
  // 對 AI 不滿、要人：「這個AI沒用，給我電話」「機器人看不懂」
  /(ai|AI|機器人|米亞|你).{0,6}(沒用|不行|很爛|好爛|看不懂|答非所問|聽不懂人話)/,
  // 短句要電話：「我想打電話問」「給我電話」「電話多少」（受訪者／所長的私人電話不在這裡，交給模型婉拒）
  /^(?!.*(受訪|所長|院長|專家|講者|教授|博士))[^?？]{0,10}(打電話|給我電話|電話多少|電話是多少|有電話嗎|聯絡電話)[^?？]{0,6}[?？!！。]*$/,
  /^(你們|工研院)?的?(公關)(是誰|是哪位|電話)[?？!！。]*$/
];
export function isHumanRequest(text) {
  const s = String(text || '').trim();
  if (!s || s.length > 30) return false;
  return HUMAN_REQUEST_RES.some(re => re.test(s));
}

// 回傳 'thanks' | 'ack' | 'menu' | 'calendar' | 'switch' | 'help' | 'contacts' | 'human' | 'industry_trend'
// | 'tech_query' | 'news' | 'org_intro' | null。
// 順序有意義：help／contacts／industry_trend／tech_query／org_intro 用完全比對最嚴格，
// 先判；calendar 跟 switch 互斥度高，誰先都行。
export function detectMetaIntent(text) {
  const s = String(text || '').trim();
  if (!s) return null;
  // 收尾語整句比對（見 detectCourtesy()）。排第一是安全的：它要求整句拆完一個字不剩，
  // 不可能吃掉任何一句帶內容的提問。
  const courtesy = detectCourtesy(s);
  if (courtesy) return courtesy;
  if (MENU_EXACT_RE.test(s)) return 'menu';
  if (HELP_EXACT_RE.test(s) || HELP_ABOUT_BOT_RE.test(s) || HELP_CAPABILITY_RE.test(s) || HELP_WHOAMI_RE.test(s)) return 'help';
  if (CONTACT_EXACT_RE.test(s) || CONTACT_ASK_RE.test(s)) return 'contacts';
  if (isHumanRequest(s)) return 'human';
  if (INDUSTRY_TREND_EXACT_RE.test(s)) return 'industry_trend';
  if (TECH_QUERY_EXACT_RE.test(s)) return 'tech_query';
  if (ORG_INTRO_RE.test(s)) return 'org_intro';
  if (isLatestNewsQuestion(s)) return 'news';
  if (SWITCH_RE.test(s)) return 'switch';
  // EVENT_LOCAL_RE：「這場還有哪些活動」問的是這一場的議程，不是全站場次表，見該處說明
  if (CALENDAR_RE.test(s) && !EVENT_LOCAL_RE.test(s)) return 'calendar';
  return null;
}

// 活動名稱比對用的正規化：拿掉空白與各種括號、標點，這樣「經濟部四足機器人
// 國產研發平台發表記者會」跟記者手打的「經濟部四足機器人 國產研發平台發表記者會」
// 會是同一個字串。不做繁簡轉換——場次名稱都是繁體，多這層只會多一個出錯的地方。
function normalizeName(s) {
  return String(s || '')
    .toLowerCase()
    .replace(/[\s　「」『』《》〈〉()（）[\]【】{}，,、。.!！?？:：;；~～\-—_|｜'"'']/g, '');
}

// 訊息「整句就是某一場活動的名稱」時回傳那張卡片，否則 null。
// 綁定中的記者打了別場名稱（多半是按了活動清單的快速回覆按鈕，那顆按鈕送出的
// 就是完整活動名稱）要能直接換過去，不然他會被鎖在原本那場、怎麼打都沒反應。
//
// 判斷刻意保守，寧可不換也不要換錯：
//   - 有問號、或用疑問詞開頭 → 這是提問不是選台，直接放棄
//   - 正規化後短於 6 個字 → 「半導體」這種詞太容易同時是提問內容，不當作選台
//   - 命中超過一場 → 不猜，交給呼叫端去問記者是哪一場
export function matchEventByName(text, cards, excludeId) {
  const raw = String(text || '').trim();
  if (!raw || raw.length > 60) return null;
  if (/[?？]/.test(raw)) return null;
  if (QUESTION_LEAD_RE.test(raw)) return null;

  const q = normalizeName(raw);
  if (q.length < 6) return null;

  const pool = (cards || []).filter(c => c && c.id && c.id !== excludeId);

  // 完全相同優先：快速回覆／圖文選單按鈕送出的就是完整名稱，這條會命中
  const exact = pool.filter(c => normalizeName(c.name) === q);
  if (exact.length === 1) return exact[0];
  if (exact.length > 1) return null;

  // 記者只打得出部分名稱時的退路
  const partial = pool.filter(c => normalizeName(c.name).includes(q));
  return partial.length === 1 ? partial[0] : null;
}

// 句子裡「點名」了哪一場（批次 75，職員「記住：眺望研討會的聯絡人是⋯⋯」用）。
// 跟 matchEventByName() 不同，那支要求整句就是活動名稱；這支從一句話裡找。
// 做法：活動名稱拿掉通用字（記者會、研討會、技術、產業⋯⋯、年份）剩下的特徵片段，
// 取 2～4 字的窗口去比對。只在**唯一一場**命中時回傳，兩場都像就不猜。
const EVENT_GENERIC_WORDS = /發表記者會|記者會|發表會|研討會|論壇|說明會|典禮|展覽|大會|解決方案|技術|產業|發展|趨勢|應用|前瞻|國際|平台|研發|年度|成果|國產|新一代|\d+/g;
export function findEventMentioned(text, cards) {
  const q = normalizeName(text);
  if (!q) return null;
  const hits = (cards || []).filter(c => {
    const segs = normalizeName(c?.name).split(EVENT_GENERIC_WORDS).filter(x => x.length >= 2);
    return segs.some(seg => {
      const w = Math.min(4, seg.length);
      for (let i = 0; i + w <= seg.length; i++) if (q.includes(seg.slice(i, i + w))) return true;
      return false;
    });
  });
  return hits.length === 1 ? hits[0] : null;
}

