// 「回首頁」；「換一場活動」等舊講法保留在這條規則裡繼續認得，記者手打舊講法、或
// HELP_TEXT／歡迎卡以外的地方還留著舊字眼都不會突然失效——跟批次 21「使用說明／
// 活動照片」換按鈕位置時的原則一樣：換掉的入口不會真的消失，只是不再是主要講法。
//
// ⚠️ 盤點時實測到的誤判（批次 57），而且是這條路上最貴的一種：舊規則的
// 「(換|切換|改) + 個」沒有綁任何名詞，於是——
//   「換一個問題」「我換個問題好了」「可以換個說法嗎」「換一個角度看」「改一個問法」
// 全部命中 switch。命中 switch 不是回一句話而已，是 clearBinding()：記者好不容易
// 掃 QR 綁上的那一場**被清掉**，畫面跳回全站活動清單。而「換個問題」正好是記者最
// 自然的轉場語，等於他每講一次這句話就被踢回首頁一次。
//
// 修法是把「個」跟名詞綁在一起：只有「換個活動／換個場次／換個記者會」才算換場，
// 光是「換個」什麼都不算。「換一場／換場／切換活動」這些原本認得的講法一個都沒少。
// 另外給裸字「場」補一個否定前瞻：「記者會換場地了嗎」是在問這場活動的事（正常提問），
// 不是要換一場——舊規則會把它當成換場，一樣清掉綁定。
