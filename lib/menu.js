//
// 主動盤點再補上「聯絡呢／聯繫呢／採訪呢」——同一個「主題詞 + 呢／嗎」句型（見
// CALENDAR_RE 開頭的說明），這三個詞跟「邀訪」「窗口」一樣是這顆按鈕底下記者會拿來
// 口語代稱的講法。「媒體」刻意不比照辦理：「媒體」單獨兩個字太泛（「這場媒體效應
