// 記者端的「跳出本場」意圖、使用說明文案、歡迎圖卡、圖文選單定義。
//
// 為什麼這裡的意圖判斷是純關鍵字、不呼叫 AI：
// lib/router.js 那支 routeIntent() 只在「沒有綁定」時跑一次，成本可以接受。但綁定
// 之後每一則訊息都是正式提問，如果為了判斷「這句是不是想換一場」而在每則問題前面
// 多打一次 Haiku，等於把所有記者的每一次提問都變慢、也多一份帳單，而真正會用到的
// 只有極少數幾句。這幾句又剛好都是我們自己控制的字串（圖文選單與快速回覆按鈕送出
// 的就是下面這些詞），關鍵字比對可以 100% 命中，不需要語意理解。
//
// 誤判的方向也刻意選過：寧可漏判（記者的「換一場」沒被認出來 → 當成提問，AI 會說
// 這場資料裡沒有，記者再打一次即可），也不要誤判（真正的提問被當成指令 → 記者的
// 問題從沒被回答，就是 handleEvent 裡 ask_name 那個已經修過一次的坑）。所以下面
// 每條規則都往「嚴格」的方向調。

// 問活動列表。「最近活動」「其他活動」「有哪些場次」都算。
// 第一段刻意要求時間／範圍詞（最近、其他、所有…）緊接著活動類詞，才不會把
// 「這場活動的重點」這種正常提問吃掉。
//
// 主動盤點（不是個別回報，是順著「技術呢／趨勢呢／邀訪呢」這一系列回報，回頭檢查
// 還有沒有同一種句型的漏網之魚）：「活動呢／場次呢／記者會呢」是跟已修的那幾句
// 同一個「主題詞 + 語助詞」句型，之前沒補到——群組續問視窗內打這句一樣會掉進
// routeIntent() 判成 other 被安靜擋掉。用 `^...(呢|嗎)$` 全字串錨定新增（跟
// TECH_QUERY_EXACT_RE 的 `^技術(呢|嗎)$` 同一個寫法），只認「整句剛好就是這幾個
// 字」，不會誤觸「這場活動呢，我還想問別的」這種「呢」當句中語氣詞（不是疑問句
// 尾）的正常說法——那句不會整句剛好等於「活動呢」，錨定確保不會被截頭符合。
const CALENDAR_RE = /(最近|近期|其他|其它|別的|所有|全部|還有|之後|未來)\s*(有哪些|有什麼|哪些|什麼)?\s*(活動|場次|記者會)|(活動|場次)\s*(列表|清單|一覽|行事曆)|(有哪些|有什麼)\s*(活動|場次|記者會)|^(活動|場次|記者會)(呢|嗎)$/;

// ⚠️ 盤點時實測到的誤判（批次 57）：上面那條完全沒有錨定，於是任何一句「⋯有哪些
// 活動⋯」都會被當成「請列出全站有哪幾場記者會」——
//   「這場記者會還有哪些活動安排？」「現場還有什麼活動可以參加？」
//   「這次記者會有哪些活動內容」「請問展區還有哪些活動」「會後還有其他活動嗎」
// 這五句問的都是**這一場裡面**的事（議程、動線），拿到的卻是全站場次表。這正是
// 一路被回報的那種答非所問，只是這次是我們自己的規則造成的。
//
// 判準：句子裡出現「這一場／這個現場」的指稱詞，或「活動」後面接的是議程類名詞
// （安排、流程、內容…），那就是在問這一場，不是在問行事曆。
//
// ⚠️ 收緊會不會製造漏判？不會——api/line.js 那邊同一批補上了「routeIntent() 判成
// calendar 時，綁定中也接得住」的分支（以前只有沒綁定時才接得到）。規則負責保證
// 按鈕與固定講法 100% 命中，AI 負責涵蓋規則想不到的講法，正是 CLAUDE.md 第 2 條
// 講的分工。時間詞（今天／明天／這個月）刻意不列進來：「明天有哪些活動」問的
// 確實是行事曆。
