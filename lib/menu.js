// 記者端的「跳出本場」意圖、使用說明文案、歡迎圖卡、圖文選單定義。
//
// 為什麼這裡的意圖判斷是純關鍵字、不呼叫 AI：
// lib/router.js 那支 routeIntent() 只在「沒有綁定」時跑一次，成本可以接受。但綁定
// 之後每一則訊息都是正式提問，如果為了判斷「這句是不是想換一場」而在每則問題前面
// 多打一次 Haiku，等於把所有記者的每一次提問都變慢、也多一份帳單，而真正會用到的
// 只有極少數幾句。這幾句又剛好都是我們自己控制的字串（圖文選單與快速回覆按鈕送出
// 的就是下面這些詞），關鍵字比對可以 100% 命中，不需要語意理解。
//
// 誤判的方向也刻意選過：寧可漏判（記者的「換一場」沒被認出來 → 當成提問，AI 會說
// 這場資料裡沒有，記者再打一次即可），也不要誤判（真正的提問被當成指令 → 記者的
// 問題從沒被回答，就是 handleEvent 裡 ask_name 那個已經修過一次的坑）。所以下面
// 每條規則都往「嚴格」的方向調。

// 問活動列表。「最近活動」「其他活動」「有哪些場次」都算。
// 第一段刻意要求時間／範圍詞（最近、其他、所有…）緊接著活動類詞，才不會把
// 「這場活動的重點」這種正常提問吃掉。
//
// 主動盤點（不是個別回報，是順著「技術呢／趨勢呢／邀訪呢」這一系列回報，回頭檢查
// 還有沒有同一種句型的漏網之魚）：「活動呢／場次呢／記者會呢」是跟已修的那幾句
// 同一個「主題詞 + 語助詞」句型，之前沒補到——群組續問視窗內打這句一樣會掉進
// routeIntent() 判成 other 被安靜擋掉。用 `^...(呢|嗎)$` 全字串錨定新增（跟
// TECH_QUERY_EXACT_RE 的 `^技術(呢|嗎)$` 同一個寫法），只認「整句剛好就是這幾個
// 字」，不會誤觸「這場活動呢，我還想問別的」這種「呢」當句中語氣詞（不是疑問句
// 尾）的正常說法——那句不會整句剛好等於「活動呢」，錨定確保不會被截頭符合。
const CALENDAR_RE = /(最近|近期|其他|其它|別的|所有|全部|還有|之後|未來)\s*(有哪些|有什麼|哪些|什麼)?\s*(活動|場次|記者會)|(活動|場次)\s*(列表|清單|一覽|行事曆)|(有哪些|有什麼)\s*(活動|場次|記者會)|^(活動|場次|記者會)(呢|嗎)$/;

// ⚠️ 盤點時實測到的誤判（批次 57）：上面那條完全沒有錨定，於是任何一句「⋯有哪些
// 活動⋯」都會被當成「請列出全站有哪幾場記者會」——
//   「這場記者會還有哪些活動安排？」「現場還有什麼活動可以參加？」
//   「這次記者會有哪些活動內容」「請問展區還有哪些活動」「會後還有其他活動嗎」
// 這五句問的都是**這一場裡面**的事（議程、動線），拿到的卻是全站場次表。這正是
// 一路被回報的那種答非所問，只是這次是我們自己的規則造成的。
//
// 判準：句子裡出現「這一場／這個現場」的指稱詞，或「活動」後面接的是議程類名詞
// （安排、流程、內容…），那就是在問這一場，不是在問行事曆。
//
// ⚠️ 收緊會不會製造漏判？不會——api/line.js 那邊同一批補上了「routeIntent() 判成
// calendar 時，綁定中也接得住」的分支（以前只有沒綁定時才接得到）。規則負責保證
// 按鈕與固定講法 100% 命中，AI 負責涵蓋規則想不到的講法，正是 CLAUDE.md 第 2 條
// 講的分工。時間詞（今天／明天／這個月）刻意不列進來：「明天有哪些活動」問的
// 確實是行事曆。
const EVENT_LOCAL_RE = /這場|這次|本場|本次|該場|那場|現場|會場|展場|展區|場內|會後|會前|當天|活動\s*(安排|流程|內容|議程|行程|規劃|重點|亮點|時間表)/;

// 想換一場。沒有「換」「切換」這類動詞就不算——只打「別場」不會誤觸。
//
// 回報的意見：這顆按鈕原本叫「換一場活動」，但其實這個帳號不是只能問活動——還有
// 產業趨勢分析、想問什麼技術、媒體邀訪需求，只用「換一場活動」描述，範圍寫得比
// 實際功能窄。按鈕改名成「回首頁」（見下面 REPORTER_MENU），送出的文字也跟著改成
// 「回首頁」；「換一場活動」等舊講法保留在這條規則裡繼續認得，記者手打舊講法、或
// HELP_TEXT／歡迎卡以外的地方還留著舊字眼都不會突然失效——跟批次 21「使用說明／
// 活動照片」換按鈕位置時的原則一樣：換掉的入口不會真的消失，只是不再是主要講法。
//
// ⚠️ 盤點時實測到的誤判（批次 57），而且是這條路上最貴的一種：舊規則的
// 「(換|切換|改) + 個」沒有綁任何名詞，於是——
//   「換一個問題」「我換個問題好了」「可以換個說法嗎」「換一個角度看」「改一個問法」
// 全部命中 switch。命中 switch 不是回一句話而已，是 clearBinding()：記者好不容易
// 掃 QR 綁上的那一場**被清掉**，畫面跳回全站活動清單。而「換個問題」正好是記者最
// 自然的轉場語，等於他每講一次這句話就被踢回首頁一次。
//
// 修法是把「個」跟名詞綁在一起：只有「換個活動／換個場次／換個記者會」才算換場，
// 光是「換個」什麼都不算。「換一場／換場／切換活動」這些原本認得的講法一個都沒少。
// 另外給裸字「場」補一個否定前瞻：「記者會換場地了嗎」是在問這場活動的事（正常提問），
// 不是要換一場——舊規則會把它當成換場，一樣清掉綁定。
const SWITCH_RE = /(換|切換|改)\s*(成|到)?\s*(一)?\s*(別場|其他場|其它場)|(換|切換|改)\s*(成|到)?\s*(一)?\s*場(?!地|合|面|景|所|域|館)|(換|切換|改)\s*(成|到)?\s*(一)?\s*(個|下)?\s*(活動|記者會|場次)|重新選擇|不是這場|不是問這場|解除綁定|離開這場|回首頁|回到首頁|回主選單/;

// 使用說明。這條最容易誤傷（「這技術怎麼用」也含「怎麼用」），所以只認
// 「整句就是在問怎麼用」的完全比對，外加明確指名這個帳號／機器人的問法。
//
// 主動盤點補上的「說明呢／教學呢／功能呢」等——跟 CALENDAR_RE 那條同一次盤點（見
// 該處說明），只挑「名詞 + 呢／嗎」語意不會變的字（說明、教學、功能、使用方式這類
// 名詞，「呢／嗎」接上去單純是「那說明呢／有功能嗎」的省略問法）。刻意不對清單裡
// 的動詞片語（怎麼用、不會用、不知道怎麼用…）做同樣的事——「不會用嗎」接了「嗎」
// 語意會整個反過來，變成在問對方「你不會用嗎」，不是在問「我不會用，怎麼辦」，這種
// 加了語助詞反而改變句意的不能比照辦理。
const HELP_EXACT_RE = /^(說明|使用說明|操作說明|help|怎麼用|要怎麼用|該怎麼用|怎麼使用|如何使用|使用方式|功能|有什麼功能|教學|使用教學|新手教學|不會用|不知道怎麼用)[?？!！。]?$|^(說明|使用說明|操作說明|教學|使用教學|新手教學|功能|使用方式)(呢|嗎)$/i;
// 「你」「這裡」這兩個指稱太寬（記者也可能拿來指技術本身），所以這條要求「問句到此為止」——
// 用 $ 錨在結尾，而不是限制長度。差別就在動詞後面還有沒有東西：
//   「你要怎麼用」「這個帳號怎麼用」→ 在問這個帳號的用法，命中
//   「你怎麼用這套資料判斷哪家廠商有優勢」→ 動詞後面還接著受詞，是在問內容，不命中
const HELP_ABOUT_BOT_RE = /(這個(帳號|機器人|助理)|小幫手|小特派|你|這裡)\s*(要|該)?\s*(怎麼|如何)\s*(用|使用|操作|開始|發問|提問)[?？!！。]?$/;

// 實際回報的答非所問：群組裡 @ 問「妳能幫我什麼」，因為不含「怎麼／如何」，
// HELP_ABOUT_BOT_RE 接不住，掉進 routeIntent()，被判成 other，回一句「不確定您
// 想問哪一場活動」——記者問的明明是「你能做什麼」，卻拿到一句跟問題完全對不上的
// 回覆。這條專門接「能力題」（你/妳 能／可以／會 做什麼），跟 HELP_ABOUT_BOT_RE
// 同一個保守原則：$ 錨在結尾，只認「問句到此為止」的完整短句，「你能不能查一下
// 這場記者會幾點開始」這種問句後面還接著具體內容的正常提問不會誤觸。
//
// 實際回報的第二種落空：群組續問視窗內（沒有再 @）打「你能做啥」，完全沒有任何
// 回覆——不是續問視窗本身沒接住（見 handleGroupEvent() 的說明，那段是好的），是
// 這句話用口語的「啥」代替「什麼」，原本只認「什麼｜哪些」的必要群組沒對到，一樣
// 掉進 routeIntent() 被判成 other；群組裡沒被直接 @ 到時，other 是安靜門檻
// （silentOnOther，見 handleUnbound() 的說明），於是變成「看起來像沒接住續問視窗」
// 的假象，其實是這句話從一開始就沒被 detectMetaIntent() 認出來是在問能力。把「啥」
// 併進同一個必要群組即可，跟「什麼／哪些」同樣要求問句到此為止，不會擴大誤觸範圍。
const HELP_CAPABILITY_RE = /^(你|妳|這個(帳號|機器人|助理)|小幫手|小特派)\s*(能|可以|會)\s*(幫我|幫上|提供|回答|做)?\s*(什麼|哪些|啥)(忙|事|功能|服務)?(嗎|呢)?[?？!！～~。]?$/;
// 問「你是誰」「妳是什麼」——第一次遇到這個帳號時很自然會問的開場白，跟能力題
// 一樣不該落到「不確定您想問哪一場活動」這種答非所問的萬用回覆。
const HELP_WHOAMI_RE = /^(你|妳)\s*是(誰|什麼|哪位|做什麼的|什麼的)(嗎|呢)?[?？!！～~。]?$/;

// 邀訪聯絡窗口。這句幾乎只會來自「媒體邀訪需求」這顆固定按鈕（見 api/line.js 的
// eventQuickChips()），所以用完全比對——記者正常提問不會整句剛好等於這幾個詞。
//
// 「邀訪呢／窗口呢」這種口語追問跟 TECH_QUERY_EXACT_RE 補的「技術呢」同一次盤點
// 順手補上（見那條規則的說明）：確認完「技術呢」這個實際回報的落空之後，順著同一
// 個「主題詞 + 語助詞」句型檢查了其他幾類固定觸發詞，「邀訪」「窗口」是這批固定詞
// 裡同樣可能被口語追問到的（「那邀訪窗口呢」的省略講法），一併補上以防之後被回報
// 同一種問題；「產業趨勢分析」那組也一併看了，見下面 INDUSTRY_TREND_EXACT_RE。
// 「窗口」不在上面主要的完全比對清單裡（只有搭配「聯絡／聯繫／分工」的複合詞），
// 這裡刻意只接「窗口呢／窗口嗎」這種帶語助詞的講法，不讓裸詞「窗口」單獨也命中——
// 跟 TECH_QUERY_EXACT_RE 不讓裸詞「技術」命中同一個理由，裸詞太容易出現在別的
