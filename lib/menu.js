// 實際回報（附截圖）：群組裡打「米亞 最近工研院有哪些新聞」，米亞回的是【近期活動】
// 行事曆。記者又追問一次「最近發的新聞稿麼」。這是答非所問：問的是新聞稿，回的是
// 記者會場次表——兩件事在這個帳號裡是不同的資料來源（新聞稿在工研院官網新聞中心，
// 場次在 events 表）。
//
// 根因：這句話沒對到任何規則，掉進 routeIntent()，AI 看到「最近⋯有哪些」這個跟
// 「最近有哪些活動」幾乎一樣的句型就判成 calendar。而 lib/itri-news.js 的
// fetchItriNews() 早就留好了「不給關鍵字就回最新新聞」這條路（那支的註解寫著
// 「這個分支是給之後萬一有『不指定技術、直接看工研院最新動態』需求時的退路」），
// 只是從來沒有入口叫得到它。
//
// ⚠️ 判斷方式跟其他 *_EXACT_RE 一樣嚴，但改用「扣掉之後還剩什麼」而不是一條長
// regex：把核心詞（新聞／新聞稿／消息）拿掉，再把時間詞、疑問詞、語助詞、「工研院」
// 全部扣掉，如果一個字都不剩，那就是在問「最新新聞」這件事本身。只要還剩下任何字
// （「半導體」「這場」），那就是有主題的問題，不歸這裡管——「半導體最近有什麼新聞」
// 要走 tech_query 拿關鍵字去搜，「這場的新聞稿」要走該場活動的問答。
// 這個寫法比長 regex 好維護，也天然擋掉了誤判：漏收一個語助詞只會讓這條不命中
// （退回原本的 AI 路由），不會反過來把有主題的問題吃掉。
// ⚠️ 核心詞刻意只收「新聞稿」「新聞」，不收「消息」。群組裡命中 detectMetaIntent()
// 就會回答（見 api/line.js handleGroupMessage()），而「最近有什麼消息」在記者群裡
// 十之八九是人在問人，不是在叫米亞——多收一個口語詞換來的是米亞插話，划不來。
const NEWS_CORE_RE = /新聞稿|新聞/g;
const NEWS_FILLER_RE = /米亞|工研院|itri|最近|近期|最新|這陣子|這幾天|今天|本週|這週|這個月|有哪些|有那些|有什麼|有沒有|哪些|那些|什麼|發表|發布|發佈|發過|發的|發了|出了|新的|請問|想看|想知道|給我|有|發|的|了|嗎|呢|麼|沒|吧|喔|press release|news|[\s?？!！。，,、~～]/gi;

export function isLatestNewsQuestion(text) {
  const s = String(text || '').trim();
  if (!s || s.length > 30) return false;          // 太長多半是一整句有主題的提問
  const withoutCore = s.replace(NEWS_CORE_RE, '').trim();
  if (withoutCore === s) return false;            // 根本沒提到新聞／消息
  // ⚠️ 裸詞「新聞」刻意不命中，理由跟上面 TECH_QUERY_EXACT_RE 不讓裸詞「技術」命中
  // 一樣：兩個字太容易是別句話的一部分（邀訪窗口的關鍵字裡就有「新聞稿」）。要有
  // 時間詞或疑問語氣才算一句在問「最近有什麼新聞」的話。
  if (!withoutCore) return false;
  return withoutCore.replace(NEWS_FILLER_RE, '').trim() === '';
}

// 提問語氣的開頭詞——用來擋掉「把一句問題誤認成活動名稱」。跟 api/line.js 的
// looksLikeNameOrSkip() 是同一類防線，但那支管的是媒體名稱，這支管的是活動名稱，
// 兩邊的誤判後果不同（那邊是少記一個媒體名，這邊是整個換錯場次），所以分開維護。
const QUESTION_LEAD_RE = /^(請問|為什麼|為何|什麼|怎麼|如何|哪裡|哪一|哪些|何時|多少|是否|能不能|可不可以|可以|會不會|有沒有|給我|請給|麻煩|幫我|提供|想問|想知道|想要|需要|介紹|說明一下)/;

// 回傳 'calendar' | 'switch' | 'help' | 'contacts' | 'industry_trend' | 'tech_query'
// | 'news' | null。
// 順序有意義：help／contacts／industry_trend／tech_query 用完全比對最嚴格，先判；
// calendar 跟 switch 互斥度高，誰先都行。
export function detectMetaIntent(text) {
  const s = String(text || '').trim();
  if (!s) return null;
  if (HELP_EXACT_RE.test(s) || HELP_ABOUT_BOT_RE.test(s) || HELP_CAPABILITY_RE.test(s) || HELP_WHOAMI_RE.test(s)) return 'help';
  if (CONTACT_EXACT_RE.test(s)) return 'contacts';
  if (INDUSTRY_TREND_EXACT_RE.test(s)) return 'industry_trend';
  if (TECH_QUERY_EXACT_RE.test(s)) return 'tech_query';
  if (isLatestNewsQuestion(s)) return 'news';
  if (SWITCH_RE.test(s)) return 'switch';
  // EVENT_LOCAL_RE：「這場還有哪些活動」問的是這一場的議程，不是全站場次表，見該處說明
  if (CALENDAR_RE.test(s) && !EVENT_LOCAL_RE.test(s)) return 'calendar';
  return null;
}

// 活動名稱比對用的正規化：拿掉空白與各種括號、標點，這樣「經濟部四足機器人
// 國產研發平台發表記者會」跟記者手打的「經濟部四足機器人 國產研發平台發表記者會」
// 會是同一個字串。不做繁簡轉換——場次名稱都是繁體，多這層只會多一個出錯的地方。
function normalizeName(s) {
  return String(s || '')
    .toLowerCase()
    .replace(/[\s　「」『』《》〈〉()（）[\]【】{}，,、。.!！?？:：;；~～\-—_|｜'"'']/g, '');
}

// 訊息「整句就是某一場活動的名稱」時回傳那張卡片，否則 null。
// 綁定中的記者打了別場名稱（多半是按了活動清單的快速回覆按鈕，那顆按鈕送出的
// 就是完整活動名稱）要能直接換過去，不然他會被鎖在原本那場、怎麼打都沒反應。
//
// 判斷刻意保守，寧可不換也不要換錯：
//   - 有問號、或用疑問詞開頭 → 這是提問不是選台，直接放棄
//   - 正規化後短於 6 個字 → 「半導體」這種詞太容易同時是提問內容，不當作選台
//   - 命中超過一場 → 不猜，交給呼叫端去問記者是哪一場
export function matchEventByName(text, cards, excludeId) {
  const raw = String(text || '').trim();
  if (!raw || raw.length > 60) return null;
  if (/[?？]/.test(raw)) return null;
  if (QUESTION_LEAD_RE.test(raw)) return null;

  const q = normalizeName(raw);
  if (q.length < 6) return null;

  const pool = (cards || []).filter(c => c && c.id && c.id !== excludeId);

  // 完全相同優先：快速回覆／圖文選單按鈕送出的就是完整名稱，這條會命中
  const exact = pool.filter(c => normalizeName(c.name) === q);
  if (exact.length === 1) return exact[0];
  if (exact.length > 1) return null;

  // 記者只打得出部分名稱時的退路
  const partial = pool.filter(c => normalizeName(c.name).includes(q));
  return partial.length === 1 ? partial[0] : null;
}

